"use strict";
/**
 * شارةُ الطرفيّة ورسالتُها [DR-03] — علاجُ تجربةٍ لقيدٍ منبعيٍّ مؤكَّد.
 *
 * ## ما تغيّر بعد [DR-05/ب] — وما بقي
 *
 * صار `terminal.integrated.gpuAcceleration` = `off`، فيرسم xterm بمسار DOM لا
 * بـWebGL. ومسارُ DOM يضع كلَّ مقطعٍ متجانسِ الأنماط في عنصرٍ واحد، فيتولّاه محرّكُ
 * النصّ في المتصفّح: **الحروفُ تتّصل والترتيبُ يمينيٌّ صحيح** — مقيسٌ على المشحون.
 *
 * **والباقي هو سببُ بقاء هذه الوحدة**: الصفُّ وحدةُ الترتيب. سطرٌ عربيٌّ طويلٌ يلتفّ
 * على أكثر من صفٍّ يُرتَّب كلُّ صفٍّ منه وحدَه، فينكسر التتابعُ عند حدّ الالتفاف
 * (قِيس: ثلاثةُ صفوفٍ لجملةٍ واحدة). ونصُّ الشارة صِيغ من جديدٍ على هذا المقيس:
 * «مقلوبة» لم تعد صادقةً بعد التحويل، **وشارةٌ تصف عطبًا زال تُفقِد الثقةَ بكلّ
 * شارةٍ أخرى**.
 *
 * ## القيدُ ومَن يدفع ثمنَه
 * `@xterm/xterm` بلا خيارِ اتّجاهٍ أصلًا، وجردُنا يصنّفه بصدقٍ **خارجَ الطبقة**. لكنّ
 * التصنيفَ ليس علاجَ تجربة. ضعْ نفسَك مكانَ من يرى في الطرفيّة سطرًا عربيًّا
 * يطبعه برنامجُه مبعثرًا عند الالتفاف: هو لا يعرف `xterm`، ولا يعرف أنّ العطبَ في مكتبةِ
 * طرفيّةٍ منبعيّة — **فيستنتج أنّ برنامجَه أو محرابًا لا يُخرِج العربيّةَ صحيحة**. وهذه لحظةُ
 * فقدِ ثقةٍ لا تُستردّ بوثيقةٍ في `docs/`.
 *
 * ## ما نفعله (شقّان)
 *   (أ) **شارةٌ في شريط الحالة** ما دامت طرفيّةٌ مفتوحة، فالحدُّ مرئيٌّ لا صامت — **ولها
 *       مخرَج**: من أخفاها بقي له أمرٌ يعيدها. شارةٌ دائمةٌ بلا مقبضٍ تُدرِّب على العمى،
 *       وهو عينُ ما بُني كاشفُ `BS-01` لتفاديه.
 *   (ب) **رسالةٌ لمرّةٍ واحدة** حين تُفتَح طرفيّةٌ **والمحرّرُ النشط فيه عربيّة** — لا عند
 *       كلّ طرفيّةٍ تُفتَح لأمرِ `git` في مشروعٍ لاتينيّ. الفرصةُ واحدةٌ للأبد، فلا تُحرَق في
 *       غير سياقها. وتُسمّي القيدَ منبعيًّا صراحةً فلا يُحمَّل البرنامجُ وزرَ غيرِه.
 *
 * لا رقعةَ نواةٍ ولا مسَّ بالمنبع — الطبقةُ الأولى وحدَها.
 */

/** مفتاحُ الحالة: هل عُرِضت رسالةُ الطرفيّة مرّةً على هذا الملفّ الشخصيّ؟ */
const STATE_KEY = "mihrab.terminal.bidiNoticeShown";
/** مفتاحُ الحالة: هل أخفى المستخدمُ الشارةَ عمدًا؟ (مخرَجُ من لا يريد تذكيرًا دائمًا.) */
const BADGE_HIDDEN_KEY = "mihrab.terminal.badgeHidden";
/** أولويّةُ شارةِ شريط الحالة — بعيدًا عن افتراضيّات اللغة والترميز. */
const STATUS_PRIORITY = 90;
/** سياقُ الرسالة: المحرّرُ النشط فيه حرفٌ عربيّ (وحدةٌ مشتركةٌ مع رسالة المقارنة). */
const { hasArabic } = require("./arabic-context.js");
/** أمرُ إعادة إظهار الشارة — المقبضُ الذي يجعل الإخفاءَ قرارًا لا بابًا مغلَقًا. */
const SHOW_AGAIN_CMD = "mihrab.showTerminalDirectionNotice";

const COPY = {
  // نصُّ الشارة يصف **ما يراه المستخدم** لا ما ينقص المكتبة.
  badge: "$(warning) العربيّة تنكسر عند التفاف السطر",
  // اسمٌ يظهر في «إدارة عناصر شريط الحالة» — بدونه لا يعرف الخبيرُ ما الذي يخفيه.
  itemName: "اتّجاه العربيّة في الطرفيّة",
  ariaLabel: "سطرٌ عربيٌّ يلتفّ في الطرفيّة ينكسر ترتيبُه — قيدٌ في مكتبة الطرفيّة المنبعيّة.",
  // **القيدُ مسمًّى بمصدره في الجملة الأولى.** بلا ذلك يُحمَّل البرنامجُ وزرَ مكتبةٍ منبعيّة.
  tooltip:
    "الطرفيّةُ المدمجةُ (مكتبة xterm المنبعيّة) تُرتّب **كلَّ صفٍّ وحدَه**، فسطرٌ عربيٌّ " +
    "طويلٌ يلتفّ على أكثر من صفٍّ ينكسر تتابعُه عند حدّ الالتفاف. وهذا قيدٌ في المكتبة " +
    "لا في برنامجك.\n\n" +
    "وسِّع لوحةَ الطرفيّة أو قصِّر السطرَ لترى الجملةَ كاملةً بلا التفاف.",
  notice:
    "الطرفيّةُ المدمجةُ تُرتّب كلَّ صفٍّ وحدَه، فسطرٌ عربيٌّ طويلٌ ينكسر عند التفافه " +
    "(قيدٌ في مكتبة xterm المنبعيّة، لا في برنامجك). وسِّع اللوحةَ لترى الجملةَ كاملة.",
  dontRemind: "أخفِ هذا التنبيه",
  hidden:
    "أُخفيَ تنبيهُ الطرفيّة. لإعادته: لوحةُ الأوامر ← «محراب: أظهِر تنبيه اتّجاه الطرفيّة».",
  shownAgain: "أُعيد تنبيهُ اتّجاه الطرفيّة.",
};

/**
 * يبني شارةَ شريط الحالة ويُبقيها متزامنةً مع وجود طرفيّةٍ ومع رغبة المستخدم.
 * يعيد كائنًا فيه `dispose` و`showAgain` (يستدعيه أمرُ الإعادة).
 *
 * @param {*} vscode واجهةُ المحرّر (محقونةٌ للاختبار).
 * @param {*} memento ذاكرةُ الحالة العامّة (`context.globalState`).
 */
function activateTerminalNotice(vscode, memento) {
  const item = vscode.window.createStatusBarItem(
    vscode.StatusBarAlignment.Right,
    STATUS_PRIORITY
  );
  item.text = COPY.badge;
  item.tooltip = COPY.tooltip;
  item.name = COPY.itemName;
  // الشارةُ خبرٌ لا زرّ (لا أمرَ يُنفَّذ بالنقر)، والتلميحُ يحمل الشرحَ كاملًا.
  item.accessibilityInformation = { label: COPY.ariaLabel };
  // لا خلفيّةَ تحذيرٍ دائمة: الخلفيّةُ الصفراءُ في شريط الحالة تُقرأ **عطلًا جاريًا**،
  // وهذا **حدٌّ ثابتٌ معروف**. الأيقونةُ وحدَها تكفي للتنبيه بلا إلحاح.

  const sync = () => {
    const hidden = memento && memento.get(BADGE_HIDDEN_KEY);
    const open = (vscode.window.terminals || []).length > 0;
    if (open && !hidden) item.show();
    else item.hide();
  };

  /**
   * رسالةُ المرّةِ الواحدة — **مشروطةٌ بسياقٍ عربيّ**. اللحظةُ المقصودةُ في DR-03 هي «فتحتُ
   * طرفيّةً وأنا أعمل على نصٍّ عربيّ»، لا «فتحتُ طرفيّةً لأمرِ git في مشروعٍ لاتينيّ». ورسالةٌ
   * لمرّةٍ واحدةٍ تُحرَق إن جاءت في غير سياقها، فننتظر السياقَ ولا نحرقها.
   */
  const maybeNotice = async () => {
    if (!memento || memento.get(STATE_KEY)) return;
    const ed = vscode.window.activeTextEditor;
    if (!ed || !ed.document) return;
    if (!hasArabic(ed.document.getText())) return;
    // نسِم «عُرِضت» **قبل** الانتظار: لا نريد رسالتين لو فُتِحت طرفيّتان معًا.
    await memento.update(STATE_KEY, true);
    const pick = await vscode.window.showInformationMessage(COPY.notice, COPY.dontRemind);
    if (pick === COPY.dontRemind) {
      // الزرُّ يفعل ما يقول: يُخفي **الشارةَ** أيضًا — وهي الشيءُ الوحيدُ المتكرّر.
      await memento.update(BADGE_HIDDEN_KEY, true);
      sync();
      vscode.window.showInformationMessage(COPY.hidden);
    }
  };

  const subs = [
    item,
    // **يُعاد الوعدُ عمدًا** لا يُبتلَع: VS Code يتجاهل قيمةَ عائدِ المستمع، لكنّ إعادتَه
    // تجعل الرسالةَ **قابلةً للانتظار في الاختبار** — ورسالةٌ تُختبَر خيرٌ من رسالةٍ تُفترَض.
    vscode.window.onDidOpenTerminal(() => {
      sync();
      return maybeNotice().catch(() => {});
    }),
    vscode.window.onDidCloseTerminal(() => sync()),
  ];
  sync();

  return {
    item,
    /** أمرُ الإعادة: يُلغي الإخفاءَ ويُظهِر الشارةَ فورًا إن كانت ثمّة طرفيّة. */
    async showAgain() {
      if (memento) await memento.update(BADGE_HIDDEN_KEY, undefined);
      sync();
      vscode.window.showInformationMessage(COPY.shownAgain);
    },
    dispose() {
      for (const s of subs) {
        try {
          s.dispose();
        } catch {
          /* تجاهُلٌ مقصود عند الإغلاق */
        }
      }
    },
  };
}

module.exports = {
  activateTerminalNotice,
  STATE_KEY,
  BADGE_HIDDEN_KEY,
  STATUS_PRIORITY,
  SHOW_AGAIN_CMD,
  COPY,
};
