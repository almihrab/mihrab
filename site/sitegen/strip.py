# -*- coding: utf-8 -*-
"""تجريدُ تعليقات CSS وJS وقتَ البناء — المصدرُ يبقى بتعليله، والزائرُ لا يُنزِّله.

التعليقاتُ ‎66–71%‎ من بايتات أوراق CSS ونحو ‎60%‎ من السكربتين (قِيس 2026-11-25)، وكلُّها سجلُّ
قراراتٍ للمطوّر لا يحتاجه المتصفّح. فتُنزَع هنا عند النسخ إلى `public/assets`، ويبقى المصدرُ كما هو.

**مستقلٌّ عن ماسح الحارس** (‏`css_strip_comments` في `tests/docs/site_guard/core.py` وشاهدُ JS في `site_guard/out.py`): الحارسُ
[MIN-01] يجرّد المصدرَ بماسحه ويقارن الناتجَ بالمنشور — ولو كانا شيئًا واحدًا لشهد الماسحُ لنفسه.
ولكلّ فرعٍ هنا حالتُه في `tests/docs/test_strip.py`: المصدرُ الحاليّ لا يحوي أكثرَ هذه الأصناف،
فالحارسُ وحدَه لا يراها.

**ويرفض بصوتٍ ولا يخمّن** — كلُّ رفضٍ يوقف البناء ويُعاد صوغُ المصدر (انظر الدالّتين).
"""
import re

_QUOTED = re.compile(r"""'(?:\\.|[^'\\])*'|"(?:\\.|[^"\\])*\"""")


class StripError(ValueError):
    """مصدرٌ لا يُجرَّد بأمان — يُوقِف البناء."""


def _sep(ch, before):
    """فاصلٌ يجعل نزعَ التعليق بجانبه آمنًا: مسافةٌ، أو حدُّ الملفّ، أو رمزٌ من محرفٍ واحدٍ لا
    يلتحم بجاره — ‏`{};,:)[]>` من الجانبين، و`(` **قبل** التعليق وحده (بعده يصنع دالّة:
    ‏`rgb/**/(`). ولا يُضاف `+ . * | # -` أبدًا: تلتحم (‏`+1`، ‏`.5`، ‏`*=`، ‏`|=`)."""
    return not ch or ch.isspace() or ch in "{};,:)[]>" or (before and ch == "(")


def strip_css(src, name="?"):
    """⇒ نصُّ CSS بلا تعليقات. يرمي `StripError` بموضعٍ مسمّى عند ما لا يُجرَّد بأمان.

    ما سوى التعليقات يبقى بالبايت: السلاسلُ (‏`content: "/*"`)، و`url(` بلا اقتباس (‏`url(data:…*/…)`
    رمزٌ واحد)، والهروبُ `\\x` خارج السلسلة (محرفٌ واحدٌ لا بدايةُ تعليق). وسطرٌ لم يكن فيه إلّا تعليقٌ
    يُحذف كلُّه، وما بقي بعد التعليق من مسافةٍ في آخر السطر يُقصّ.

    ويُرفض: تعليقٌ أو سلسلةٌ أو `url(` لا تُغلَق، و`/*` داخل تعليق، و`*/` بلا `/*`، و**تعليقٌ
    ملاصقٌ من جانبيه** (لا فاصلَ على أيٍّ منهما؛ انظر `_sep`): في CSS لا يُنتج التعليقُ شيئًا فيبقى
    ما حوله رمزين، ونزعُه يلصقهما — ‏`a/**/b` محدِّدٌ واحد، و`1/**/.5em` ‏`1.5em`، و`rgb/**/(`
    دالّة — وإبدالُه بمسافةٍ يصنع مُركِّبَ السليل. لا نزعَ آمنًا.
    """
    out = []
    lines_with_comment = set()   # أرقامُ أسطر المخرَج التي نُزع منها تعليق
    i, n = 0, len(src)

    def where(pos):
        return "%s:%d" % (name, src.count("\n", 0, pos) + 1)

    while i < n:
        c, c2 = src[i], src[i:i + 2]
        if c == "\\":
            out.append(src[i:i + 2])
            i += 2
            continue
        if c2 == "/*":
            end = src.find("*/", i + 2)
            if end < 0:
                raise StripError("تعليقٌ لا يُغلَق في %s" % where(i))
            if "/*" in src[i + 2:end]:
                raise StripError("‏`/*` داخل تعليقٍ في %s — تعليقٌ يُظنّ متداخلًا" % where(i))
            prev = out[-1][-1:] if out and out[-1] else ""
            # محرفٌ مهرَّبٌ قبل التعليق (‏`\ ` أو `\{`) جزءٌ من اسمٍ لا فاصل: ‏`.a\ /**/b` اسمُه «a b»
            # إن نُزع التعليق.
            if out and out[-1].startswith("\\"):
                prev = "x"
            nxt = src[end + 2:end + 3]
            if not _sep(prev, True) and not _sep(nxt, False):
                raise StripError("تعليقٌ ملاصقٌ من جانبيه في %s (‏`%s/*…*/%s`) — نزعُه يلصق رمزين "
                                 "وإبدالُه بمسافةٍ يغيّر المحدِّد؛ يُعاد صوغُ المصدر" % (where(i), prev, nxt))
            # الأسطرُ داخل التعليق تُحذف معه؛ ويُعلَّم السطرُ الحاليّ للقصّ.
            lines_with_comment.add("".join(out).count("\n"))
            i = end + 2
            continue
        if c2 == "*/":
            raise StripError("‏`*/` بلا `/*` يسبقه في %s" % where(i))
        if c in "\"'":
            j = i + 1
            while j < n and src[j] != c:
                if src[j] == "\\":
                    j += 1
                elif src[j] == "\n":
                    raise StripError("سلسلةٌ لا تُغلَق في %s" % where(i))
                j += 1
            if j >= n:
                raise StripError("سلسلةٌ لا تُغلَق في %s" % where(i))
            out.append(src[i:j + 1])
            i = j + 1
            continue
        if src[i:i + 4].lower() == "url(":
            j = i + 4
            while j < n and src[j] in " \t\r\n":
                j += 1
            if j < n and src[j] not in "\"'":
                k = src.find(")", j)
                if k < 0:
                    raise StripError("‏`url(` لا يُغلَق في %s" % where(i))
                out.append(src[i:k + 1])
                i = k + 1
                continue
        out.append(c)
        i += 1

    res = []
    for no, line in enumerate("".join(out).split("\n")):
        if no in lines_with_comment:
            line = line.rstrip(" \t")
            if not line:
                continue           # سطرٌ لم يكن فيه إلّا تعليق
        res.append(line)
    return "\n".join(res)


def strip_js(src, name="?"):
    """⇒ JS بلا تعليقات **الأسطر الكاملة** — سطريًّا، بلا محلِّلٍ ولا تخمين.

    يُحذف سطرٌ يبدأ (بعد المسافة) بـ`//`، وكتلةٌ تبدأ في أوّل سطرها بـ`/*` حتّى السطر الذي
    تُغلَق فيه. وما سوى ذلك يبقى بالبايت، ومنه التعليقُ القصيرُ بعد شيفرةٍ في سطرها: تمييزُه
    يحتاج محلِّلًا (‏`/` قسمةٌ أو تعبيرٌ نمطيٌّ أو بدايةُ تعليق)، وما يوفّره لا يستحقّ ذلك.
    وحذفُ سطرٍ كاملٍ لا يغيّر الإدراجَ التلقائيّ للفاصلة (‏ASI): يبقى بين الجملتين سطرٌ جديد.

    **ويرفض بصوت** كلَّ ما يجعل «السطرُ يبدأ بـ`//` أو `/*`» غيرَ دالٍّ على تعليق:
    - كتلةٌ لا تُغلَق، أو شيفرةٌ بعد `*/` في سطر الإغلاق (حذفُ السطر يحذفها معه).
    - سطرٌ باقٍ يفتح `/*` ولا يغلقه: ما بعده داخلَ تعليقٍ لا يراه المجرِّد، فسطرٌ يبدأ بـ`/*` هناك
      وتُحذف كتلتُه يحذف معها إغلاقَ الأوّل فيبتلع التعليقُ الشيفرةَ بعده.
    - سطرٌ باقٍ ينتهي بـ`\\` (سلسلةٌ تمتدّ إلى السطر التالي: سطرٌ يبدأ بـ`//` فيها نصّ).
    - قالبٌ نصّيٌّ (`` ` `` خارج سلسلةٍ في سطرٍ باقٍ): سطرٌ داخله يبدأ بـ`//` نصٌّ لا تعليق.
    فإن احتيج شيءٌ من هذا يومًا وُسِّع المجرِّدُ عن قصد.

    **وحدودُه المعروفة** (السلاسلُ تُحذف من السطر قبل الفحص، والتعابيرُ النمطيّةُ لا يعرفها):
    - رفضٌ زائدٌ مسموع: تعبيرٌ نمطيٌّ أو تعليقٌ ذيليٌّ فيه `/*` بلا `*/` بعده (‏`/[/*]/`،
      ‏`// src/**/*.js`) يُرفض — يُعاد صوغُه.
    - تساهلٌ نظريّ: علامةُ اقتباسٍ داخل تعبيرٍ نمطيٍّ قبل `/*` في السطر (‏`x = /"/; /* "`) تُخفي
      الفاتحَ عن الفحص. لا يقع في المصدر، ولا يستحقّ محلِّلًا.
    """
    lines = src.split("\n")
    out = []
    i = 0
    while i < len(lines):
        st = lines[i].lstrip()
        if st.startswith("//"):
            i += 1
            continue
        if st.startswith("/*"):
            j, k = i, lines[i].index("/*") + 2
            while lines[j].find("*/", k) < 0:
                j, k = j + 1, 0
                if j >= len(lines):
                    raise StripError("تعليقٌ لا يُغلَق في %s:%d" % (name, i + 1))
            if lines[j][lines[j].find("*/", k) + 2:].strip():
                raise StripError("شيفرةٌ بعد `*/` في %s:%d — حذفُ سطر التعليق يحذفها معه" % (name, j + 1))
            i = j + 1
            continue
        bare = _QUOTED.sub("", lines[i])
        if "`" in bare:
            raise StripError("قالبٌ نصّيٌّ في %s:%d — سطرٌ داخله يبدأ بـ`//` نصٌّ لا تعليق، "
                             "والمجرِّدُ السطريّ لا يميّزه" % (name, i + 1))
        if bare.rfind("/*") > bare.rfind("*/"):
            raise StripError("تعليقٌ يُفتح في منتصف السطر ولا يُغلَق فيه في %s:%d — ما بعده داخلَ "
                             "تعليقٍ لا يراه المجرِّدُ السطريّ" % (name, i + 1))
        if lines[i].endswith("\\"):
            raise StripError("سطرٌ ينتهي بـ`\\` في %s:%d — سلسلةٌ تمتدّ إلى السطر التالي" % (name, i + 1))
        out.append(lines[i])
        i += 1
    return "\n".join(out)
