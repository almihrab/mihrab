#!/usr/bin/env bash
# نشرُ أثرِ خادمِ النفق — ما ينزّله `mihrab-tunnel` ويشغّله على جهاز المستخدم.
#
#   build/publish_server.sh /مسار/mihrab-reh-web-win32-x64-1.126.06011.tar.gz [مسارٌ آخر …]
#
# ⚠️ **والقناةُ مُجمَّدةٌ بقرارٍ ملكيّ.** البناءُ لا يحزم شيئًا ما لم تُضبَط
#    `MIHRAB_TUNNEL=yes`، وتفعيلُ النشر **لا رجعةَ فيه عمليًّا**: العنوانُ يُخبَز في
#    بايتات الـCLI ولا مستودعَ نُسَخٍ له عندنا، فكلُّ ثنائيٍّ يُشحَن بعده يشير إلى هذا
#    المضيف أبدًا. ويجرّ معه سياسةَ استبقاءٍ لم تُكتَب، وقناةَ توزيعٍ ثانيةً غيرَ
#    موصوفةٍ في `docs/سياسة-توقيع-الشيفرة.md` ولا في طلب SignPath. راجعها أوّلًا.
#
# ‏**ولماذا سكربتٌ ثانٍ ولا `publish_release.sh`؟** ذاك ينشر ما يُنزِّله **إنسانٌ من
# صفحة**: يتحقّق من معرّفات `site/data/site.json` ويكتب `releases.json` الذي يبني
# جدولَ التنزيل. وهذا ينشر ما يُنزِّله **برنامجٌ من عنوانٍ مخبوزٍ في ثنائيّ**: لا
# معرّفَ منصّةٍ له، ولا يظهر في جدول، وتخطيطُه ليس اختيارًا بل ما يبنيه
# ‏`update_service.rs` حرفيًّا. وخلطُهما يعني أنّ رفعَ خادمٍ يمسح مانيفستَ الإصدار،
# أو أن يظهر أرشيفُ خادمٍ في صفحة التنزيل صفًّا لا يعرف الزائرُ ما هو.
#
# ⚠️ **وأمنيًّا: العميلُ لا يتحقّق من بصمةٍ ولا توقيع.** `UpdateServerVersion` حقلاه
#    `name` و`version` وحدَهما، و«تحقّقُ السلامة» الوحيد في `code_server.rs` هو
#    **تشغيلُ الملفّ المنزَّل** (`--version`). فالحمايةُ الوحيدةُ TLS، ومن يملك
#    الكتابةَ في `$SRV_DIR` يملك تنفيذَ شيفرةٍ على أجهزة من شغّل النفق.
#
# التخطيطُ الذي يقرؤه الـCLI — **مُشتقٌّ من الشجرة المُرقَّعة لا مكتوبٌ هنا**:
#   `build/cli_url_shape.py` يقرأ `update_service.rs` ويعطي لاحقةَ المانيفست.
#   ورقعةُ ويندوز `41-cli-fix-update-url.patch` تُقحِم `user/` فيها، فمسارٌ مكتوبٌ
#   بيدٍ يخدم عنوانًا لا يطلبه العميلُ على منصّتنا الأولى — يُنشَر بنجاحٍ ويُخفِق
#   عند المستخدم وحدَه.
#   الأثر: `{قاعدة}/download/{name}/{app}-reh-web-{نظام}-{معماريّة}-{name}.tar.gz`
#
# و`name` يظهر في **العنوان مرّتَين**، و`version` هو ما يُخزَّن به الخادمُ في ذاكرة
# المستخدم المؤقّتة (`cache.create(&release.commit, …)` — `serve_web.rs:794`). فاسمٌ
# يتكرّر بمحتوًى مختلفٍ يترك خادمًا قديمًا يعمل إلى الأبد؛ ولهذا يُرفَض الدهسُ صراحةً.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

HOST="${MIHRAB_SITE_HOST:?عيّن MIHRAB_SITE_HOST (مثال: user@host)}"
PORT="${MIHRAB_SITE_PORT:-22}"
# ‏`${VAR-…}` لا `${VAR:-…}` — كما في (و-4ب): فراغٌ صريحٌ يعني «أطفِئ» لا «استعمل
# الافتراضيّ». والصيغتان المختلفتان بين الطرفَين تجعلان `MIHRAB_SERVER_BASE=` تُطفئ
# الخبزَ هناك وتنشر إلى الإنتاج هنا — أي طرفان يفهمان الأمرَ نفسَه على وجهَين.
BASE_URL="${MIHRAB_SERVER_BASE-https://sad-lang.org/mihrab/dl/server}"
SRV_DIR="${MIHRAB_SITE_ROOT:-/opt/sad-website}/${MIHRAB_SITE_SUBDIR:-mihrab}/dl/server"

SSH=(ssh -p "$PORT" -o BatchMode=yes)

die() { echo "❌ $*" >&2; exit 1; }
say() { echo "▶ $*"; }

[[ -n "$BASE_URL" ]] || die "‏MIHRAB_SERVER_BASE فارغةٌ صراحةً — وهي في build.sh تعني «أطفِئ النفق».
   فلا يُنشَر أثرٌ إلى قاعدةٍ لا يخبزها البناء."

(( $# >= 1 )) || die "الاستعمال: $0 <أثرٌ .tar.gz> [أثرٌ آخر …]"

for arg in "$@"; do
  case "$arg" in
    -*) die "وسيطٌ غيرُ معروف: $arg — هذا السكربتُ يأخذ مساراتِ آثارٍ لا رايات" ;;
  esac
done

# ‏`sha256sum` غيرُ موجودٍ في macOS القياسيّ — والنشرُ من جهاز ماك حالةٌ واردة
# (أثرُ `darwin-arm64` يُبنى هناك). ويُحلّ مرّةً لا في كلّ دورة.
if command -v sha256sum >/dev/null 2>&1; then _SHA=(sha256sum)
elif command -v shasum   >/dev/null 2>&1; then _SHA=(shasum -a 256)
else die "لا أداةَ بصمةٍ محلّيّة (sha256sum ولا shasum) — ولا يُرفَع ما لا يُقاس"
fi

# ولاحقةُ المانيفست تُشتقّ من الشجرة المُرقَّعة نفسِها التي بُني منها الثنائيّ.
_RS="$HERE/.upstream/vscode/cli/src/update_service.rs"
[[ -f "$_RS" ]] || die "لا شجرةَ CLI مُجهَّزة: $_RS
   ولاحقةُ المانيفست تُشتقّ منها لا تُكتَب بيد — انشر من جهاز البناء."
. "$HERE/build/lib/pybin.sh"
resolve_py_bin || exit 1
MAN_SUFFIX="$("$PY_BIN" "$HERE/build/cli_url_shape.py" "$_RS" | sed -nE 's/^MANIFEST_SUFFIX=(.*)$/\1/p')"
[[ -n "$MAN_SUFFIX" ]] || die "تعذّر اشتقاقُ لاحقة المانيفست من $_RS"

_CHECKS=()

for path in "$@"; do
  [[ -f "$path" ]] || die "ملفٌّ غير موجود: $path"
  file="$(basename "$path")"

  # ‏**الاسمُ يُفكَّك ولا يُصدَّق.** أرشيفٌ باسمٍ لا يطابق القالبَ يُرفَع بلا شكوى ثمّ
  # لا يجده الـCLI أبدًا — والعطبُ يظهر عند المستخدم بعد أشهر، لا هنا.
  #
  # ⚠️ **والنسخةُ مقيَّدةٌ كأخواتها.** كانت `(.+)` فقُبِل
  #    `mihrab-reh-web-linux-x64-1.0';id;'.tar.gz` (مقيس)، و`$name` يُبسَط داخل
  #    اقتباسٍ مفردٍ في أوامرَ `ssh` — فيُكسَر الاقتباسُ وينفَّذ أمرٌ **على خادم
  #    الموقع**. وفراغٌ في الاسم يكسر مسارَ `scp` البعيد. فلا يُقبَل إلّا ما يصلح
  #    مقطعَ مسارٍ ومحتوى JSON معًا.
  [[ "$file" =~ ^([A-Za-z0-9_.-]+)-reh-web-(win32|linux|darwin|alpine)-([A-Za-z0-9]+)-([A-Za-z0-9][A-Za-z0-9._-]*)\.tar\.gz$ ]] \
    || die "اسمٌ لا يطابق قالبَ الـCLI: $file
   المنتظَر: <app>-reh-web-<win32|linux|darwin|alpine>-<معماريّة>-<نسخة>.tar.gz
   والنسخةُ حروفٌ وأرقامٌ و . _ - فقط: الاسمُ يصير جزءًا من مسارٍ على الخادم
   ومن أمرِ صَدَفةٍ بعيد، فما لا يُقيَّد هنا يُنفَّذ هناك."
  app="${BASH_REMATCH[1]}"; os="${BASH_REMATCH[2]}"
  arch="${BASH_REMATCH[3]}"; name="${BASH_REMATCH[4]}"

  # ‏**واسمُ التطبيق يُطابَق بهويّتنا لا يُقبَل كما جاء.** أرشيفٌ باسم المنبع
  # (`vscodium-reh-web-…`) يطابق القالبَ تمامًا، ويُرفَع بلا شكوى، ويُقدَّم من
  # نطاقنا خادمًا **ليس خادمَنا**: بلا عربيّةٍ ولا اتّجاهٍ ولا لغة ص. وهو عطبٌ
  # وقع فعلًا في الثنائيّ قبل هذا (بقيت `vscodium` مفردةً بعد تصحيح المضيف).
  #
  # ‏`path.resolve` لازمة: `require` بمسارٍ لا يبدأ بـ`./` يُعامَل **اسمَ حزمةٍ**
  # فيموت بـMODULE_NOT_FOUND — والقيمةُ تصير فارغةً فيمرّ الفحصُ على كلّ شيء.
  want_app="$(node -p "require(require('path').resolve(process.argv[1])).applicationName" "$HERE/product-overrides/product.json")"
  [[ "$app" == "$want_app" ]] || die "اسمُ التطبيق في الأثر «$app» وهويّتُنا «$want_app».
   المعنى: هذا ليس خادمَنا — أو أنّ البناءَ خرج باسم المنبع. وفي الحالتَين
           يُقدَّم من نطاقنا خادمٌ بلا عربيّةٍ ولا اتّجاه [BR-05]."

  # ونقطةُ الدخول تُقاس **قبل الرفع**: أرشيفٌ بلا `bin/…` يُنزَّل كاملًا عند
  # المستخدم (مئاتُ الميغابايتات) ثمّ يُخفِق. والقياسُ هنا يكلّف ثانية.
  # والفهرسُ يُكتَب ثمّ يُقرأ ولا يُمرَّر في أنبوب: `grep -q` يغلق الأنبوبَ عند أوّل
  # تطابقٍ فيموت `tar` بـSIGPIPE، و`pipefail` يجعل حالةَ الأنبوب 141 — فيُرفَض
  # أرشيفٌ **سليم** برسالةٍ تقول إنّه بلا نقطةِ دخول. قِيس: `PIPESTATUS = 141 0`.
  _list="$(mktemp)"
  tar tzf "$path" > "$_list" 2>/dev/null || { rm -f "$_list"
    die "أرشيفٌ لا يُقرأ: $file
   ‏\`tar tzf\` أخفق قبل الرفع — فالملفُّ ليس أرشيفَ gzip أو قُطِع نسخُه.
   والرفعُ يُوقَف هنا عمدًا: لا يُقرأ عند المستخدم ما لا يُقرأ عندنا.
   أعِد إخراجَه من البناء (‏build/build.sh ط-0د1) قبل إعادة المحاولة."; }
  grep -qE "^(\./)?bin/[^/]+$" "$_list" || { rm -f "$_list"
    die "لا bin/ في جذر الأرشيف: $file — يُفكّ سليمًا ولا يُقلِع"; }
  rm -f "$_list"

  "${SSH[@]}" "$HOST" "mkdir -p '$SRV_DIR/download/$name' '$SRV_DIR/stable/$os/$arch'"

  # ‏**ولا يُدهَس أثرٌ منشور.** الترويسةُ أعلاه تسمّي الخطر ولم تكن تحرسه: نسخةٌ
  # يُعاد بناؤها بالرقم نفسِه تدهس الأرشيفَ بنجاح، فيبقى كلُّ من نزّل الخادمَ قبلًا
  # على نسخته القديمة أبدًا (مفتاحُ الذاكرة المؤقّتة الاسمُ لا المحتوى) بلا كلمة.
  _exists="$("${SSH[@]}" "$HOST" "[ -f '$SRV_DIR/download/$name/$file' ] && echo yes || echo no")"
  if [[ "$_exists" == "yes" && "${MIHRAB_FORCE_REPUBLISH:-no}" != "yes" ]]; then
    die "الأثرُ منشورٌ سلفًا بهذا الاسم: $file
   ودهسُه يترك كلَّ من نزّله على نسخته القديمة إلى الأبد. ارفع رقمَ البناء،
   أو MIHRAB_FORCE_REPUBLISH=yes إن كنت تعرف أنّ أحدًا لم ينزّله بعد."
  fi

  say "رفع $file ($(du -m "$path" | cut -f1) م.ب) …"
  # رفعٌ إلى اسمٍ مؤقّتٍ ثمّ تسميةٌ ذرّيّة: انقطاعٌ في المنتصف يجب ألّا يترك أرشيفًا
  # نصفَ مكتملٍ يحمل الاسمَ النهائيّ — وهنا خاصّةً، فالمُنزِّلُ برنامجٌ لا إنسان،
  # ولا يفتح الملفَّ ليرى أنّه ناقص: يفكّه ويُخفِق برسالةٍ لا تدلّ على السبب.
  scp -P "$PORT" -o BatchMode=yes "$path" "$HOST:$SRV_DIR/download/$name/.$file.part"

  # ‏**والبصمةُ تُقاس على الجزء قبل التسمية.** كان الترتيبُ `scp → mv → sha`،
  # فيسقط سببُ وجود `.part` كلُّه: رفعٌ عطبٌ يخرج بصفرٍ (قرصٌ امتلأ على الخادم)
  # يضع الأرشيفَ الناقصَ باسمه النهائيّ **ثمّ** يُكتشَف، ويُطلَب من المشغّل حذفُه
  # يدويًّا وقتَ ذعر. والآن: يُقاس، فإن اختلف حُذِف الجزءُ ولم يُسمَّ شيء.
  sha="$("${SSH[@]}" "$HOST" "${_SHA[0]} '$SRV_DIR/download/$name/.$file.part' | cut -d' ' -f1")"
  local_sha="$("${_SHA[@]}" "$path" | cut -d' ' -f1)"
  if [[ "$sha" != "$local_sha" ]]; then
    "${SSH[@]}" "$HOST" "rm -f '$SRV_DIR/download/$name/.$file.part'" || true
    die "بصمةُ ما وصل تخالف ما غادر:
   محلّيًّا: $local_sha
   على الخادم: $sha
   المعنى: الرفعُ عطب. وحُذِف الجزءُ المؤقّت، فلم يُسمَّ شيءٌ باسمه النهائيّ
           ولم يُخدَم لعميل. أعِد المحاولة."
  fi
  "${SSH[@]}" "$HOST" "mv '$SRV_DIR/download/$name/.$file.part' '$SRV_DIR/download/$name/$file'"
  echo "   ✓ $sha"

  # ── المانيفست يُكتب **بعد** الأثر، ذرّيًّا ──
  # الترتيبُ ليس تجميلًا: مانيفستٌ يَعِد باسمٍ لا أثرَ له يجعل كلَّ عميلٍ يقرؤه
  # يُخفِق حتّى يصل الرفعُ — نافذةٌ يظهر فيها العطبُ عند المستخدمين لا عندنا.
  # ‏**ويُبنى بـ`jq -n` لا بـ`printf`**: اسمٌ يحمل `"` أو `\` يُخرِج JSON غيرَ صالحٍ
  # فيقرؤه البناءُ التالي «200 بلا اسمٍ مقروء» ويتّهم `jq`. (والاسمُ مقيَّدٌ أعلاه،
  # وهذا حزامٌ ثانٍ لا بديلٌ عنه.)
  _man_dir="$SRV_DIR/stable/$os/$arch"
  _man_lead="${MAN_SUFFIX%/*}"
  if [[ "$_man_lead" != "$MAN_SUFFIX" ]]; then
    _man_dir="$_man_dir/$_man_lead"
    "${SSH[@]}" "$HOST" "mkdir -p '$_man_dir'"
  fi
  _man_file="${MAN_SUFFIX##*/}"
  jq -n --arg n "$name" '{name:$n,version:$n}' \
    | "${SSH[@]}" "$HOST" "cat > '$_man_dir/.latest.json.new' && mv '$_man_dir/.latest.json.new' '$_man_dir/$_man_file'"
  echo "   ✓ $BASE_URL/stable/$os/$arch/$MAN_SUFFIX ⇐ $name"
  # ‏**وسطرُ التحقّق يُجمَع في الحلقة لا يُطبَع بعدها.** كان يقرأ `$os`/`$arch`
  # خارجَها فيصف الأثرَ الأخيرَ وحدَه: من نشر ثلاثةً في نداءٍ واحدٍ يُعطى تحقّقًا
  # لواحدٍ ويصمت عن اثنَين — رسالةٌ تبدو كاملةً وهي ناقصة.
  _CHECKS+=("$BASE_URL/stable/$os/$arch/$MAN_SUFFIX")
done

echo
echo "✅ أثرُ الخادم منشور. والبناءُ التالي **يقيسه فيخبز الوجهةَ من نفسه** —"
echo "   ‏(بـMIHRAB_TUNNEL=yes؛ فالسلسلةُ مُجمَّدةٌ افتراضًا)."
echo "   وللتحقّق الآن — سطرٌ لكلّ أثرٍ رُفِع:"
printf '     curl -fsS %s\n' "${_CHECKS[@]}"
