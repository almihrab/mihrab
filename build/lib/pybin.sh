#!/usr/bin/env bash
# مفسّرُ بايثون 3 — دالّةٌ مشتركةٌ لأنّ افتراضَه كسر بناءَ لينكس مرّتين في يومٍ واحد.
#
# ‏`python` المجرَّد **غيرُ موجودٍ على أوبونتو 24.04** (‏`python3` وحدَه). وعلى توزيعاتٍ
# أقدمَ هو **بايثون 2** — وهذه أخبثُ: الأمرُ يوجد، والمُرقِّعُ يفشل بخطأِ صياغةٍ في
# ملفٍّ سليم. وقِيس الأوّلُ حيًّا مرّتين: مرّةً في `build.sh` ومرّةً في الشيفرة التي
# نحقنها في `build.sh` المنبع — وفي الثانية أشارت الرسالةُ إلى سطرٍ في المنبع، فبدت
# عطبًا فيه لا في بيئتنا.
#
# فالوجودُ لا يكفي: يُختبَر أنّه 3.x قبل قبوله. والقاعدةُ في المستودع: **لا نداءَ
# `python` مجرَّدًا في أيّ سكربت** — يُستعمل `$PY_BIN` بعد `source` هذا الملفّ.
# ويحرسها فحصُ ‏[PY-01] في الطبقة الساكنة.
#
#   . "$ROOT/build/lib/pybin.sh"
#   resolve_py_bin            # يضبط PY_BIN ويصدّره، أو يسقط برسالةٍ صريحة
#   "$PY_BIN" script.py …

# يقبل مرشّحًا واحدًا إن كان بايثون 3 عاملًا. صامتٌ: القرارُ لمن يناديه.
_py_is_py3() {
  command -v "$1" >/dev/null 2>&1 &&
    "$1" -c 'import sys; sys.exit(0 if sys.version_info[0] == 3 else 1)' 2>/dev/null
}

resolve_py_bin() {
  # المُصرَّحُ من البيئة **يُختبَر كالمُكتشَف**. وكان معفًى، وذلك عكسُ المقصود: من
  # يضبط المتغيّرَ يدويًّا أقربُ إلى الخطأ لا أبعدُ عنه (مسارٌ مطبعيّ، أو python2
  # صريح)، والإعفاءُ يؤجّل الاكتشافَ إلى أوّلِ مُرقِّعٍ بعد دقائق.
  if [ -n "${MIHRAB_PYTHON_BIN:-}" ]; then
    if _py_is_py3 "$MIHRAB_PYTHON_BIN"; then
      PY_BIN="$MIHRAB_PYTHON_BIN"
      export PY_BIN
      return 0
    fi
    echo "❌ MIHRAB_PYTHON_BIN='${MIHRAB_PYTHON_BIN}' ليس مفسّرَ بايثون 3 عاملًا." >&2
    echo "   (غيرُ موجود، أو بايثون 2 — والثاني يفشل لاحقًا بخطأِ صياغةٍ مُضلِّل.)" >&2
    return 1
  fi

  for _pc in python3 python; do
    if _py_is_py3 "$_pc"; then
      PY_BIN="$_pc"
      export PY_BIN
      return 0
    fi
  done

  echo "❌ لا مفسّرَ بايثون 3 في PATH (جُرِّب python3 ثمّ python)." >&2
  echo "   المُرقِّعاتُ والأدواتُ كلُّها بايثون؛ بلا مفسّرٍ لا بناء." >&2
  echo "   اضبط MIHRAB_PYTHON_BIN إن كان في مسارٍ آخر." >&2
  return 1
}
