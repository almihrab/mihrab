#!/usr/bin/env bash
# نشرُ موقع محراب على خادمنا → https://mihrab.dev/
#
# لماذا خادمنا لا GitHub Pages وحده؟ الثنائيّات. حزمةُ محراب تقارب ٢٠٠ ميغابايت،
# وGitHub Pages لا يستضيف مخرجاتِ بناءٍ أصلًا (والمستودعُ ليس مخزنَ ملفّات).
#
# ⚠️ **الوجهةُ `mihrab.dev` بجذرها `/opt/mihrab`** وشهادتِها وكتل nginx الخاصّة بها.
#    والخادمُ مشترَكٌ مع مواقعَ أخرى، فلا يكتب هذا
#    السكربتُ ولا أيُّ سكربتٍ هنا خارج جذر محراب.
#
# ⚠️ قيدان يفرضهما الخادم، وكلاهما مقصودٌ في هذا السكربت:
#   ٢) `dl/` **مستثنى من --delete**: الثنائيّات تُرفَع مرّةً وتبقى، وبناءُ الموقع لا
#      يعرف بها. بلا هذا الاستثناء يمسح أوّلُ نشرٍ كلَّ ملفّاتِ التنزيل.
#   ٣) النقلُ إلى مجلّدٍ مؤقّت ثمّ تبديلٌ ذرّيّ: rsync مباشرةً على المجلّد الحيّ يترك
#      الزائرَ في منتصف النقل أمام صفحةٍ بأصولٍ ناقصة.
set -euo pipefail

# ⚠️ لا قيمةَ افتراضيّة للمضيف: المستودعُ عامّ، واسمُ مستخدمٍ ومنفذٌ غيرُ قياسيٍّ
# مكتوبان في الشيفرة استطلاعٌ مجّانيٌّ لمن يقرأ. ليسا سرًّا، لكنّ نشرَهما لا يفيد
# أحدًا إلّا من يبحث عن بابٍ يطرقه. الناشرُ يعرف مضيفَه فليمرّره:
#   MIHRAB_SITE_HOST=user@host bash build/deploy_site.sh
HOST="${MIHRAB_SITE_HOST:?عيّن MIHRAB_SITE_HOST (مثال: user@host)}"
PORT="${MIHRAB_SITE_PORT:-22}"
# ── الوجهةُ صارت نطاقَ محرابٍ نفسَه ──
# كان الموقعُ يسكن مسارًا فرعيًّا على مضيفٍ آخر، وكان جذرُ `mihrab.dev` للمحرِّر. فانقلبا: الجذرُ للموقع، والمحرِّرُ إلى `app.mihrab.dev`.
ROOT="${MIHRAB_SITE_ROOT:-/opt/mihrab}"
SUB="${MIHRAB_SITE_SUBDIR:-site}"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# مفسّرُ بايثون يُحلّ ولا يُفترَض: `python` المجرَّد غائبٌ عن أوبونتو 24.04.
. "$HERE/build/lib/pybin.sh"
resolve_py_bin || exit 1
PUB="$HERE/site/public"

SSH=(ssh -p "$PORT" -o BatchMode=yes)

echo "▶ بناءُ الموقع…"
# ‏`build.py` يحترم `MIHRAB_SITE_OUT`، والنشرُ والحارسُ ثابتان على `site/public`: متغيّرٌ
# مصدَّرٌ في صدفة الناشر كان يبني في مكانٍ آخر فيُفحَص ويُشحَن `public` البائت.
unset MIHRAB_SITE_OUT
"$PY_BIN" "$HERE/site/build.py"

[[ -f "$PUB/index.html" ]] || { echo "❌ لا مخرَجَ في $PUB" >&2; exit 1; }

# ── بوّابةٌ قبل النقل: الحرّاسُ على المخرَج الذي سيُحزَم بعينه ──
# كان النشرُ يحزم ما بُني بلا سؤال، فشجرةٌ حمراءُ في CI تُنشَر خضراءَ من جهاز
# المطوّر. `--no-build` لأنّ البناءَ وقع للتوّ أعلاه وهذا المخرَجُ هو ما يُحزَم.
# ‏`MIHRAB_SITE_SKIP_GUARD=1` يتخطّاها **مُعلَنًا** لا صامتًا.
if [[ -z "${MIHRAB_SITE_SKIP_GUARD:-}" ]]; then
  echo "▶ الحرّاسُ على المخرَج…"
  "$PY_BIN" "$HERE/tests/docs/check_site.py" --no-build || {
    echo "❌ الحارسُ أحمر — لا نشرَ لشجرةٍ حمراء (‏MIHRAB_SITE_SKIP_GUARD=1 يتخطّى مُعلَنًا)" >&2; exit 1; }
else
  echo "⏭️  الحرّاسُ متخطَّون مُعلَنًا (MIHRAB_SITE_SKIP_GUARD)"
fi

DEST="$ROOT/$SUB"
STAGE="$ROOT/.$SUB.new"

echo "▶ النقلُ إلى $HOST:$STAGE …"
"${SSH[@]}" "$HOST" "rm -rf '$STAGE' && mkdir -p '$STAGE' '$DEST/dl'"

# نبذر المرحلةَ بـ dl/ الحاليّ (روابطٌ صلبة، بلا نقلِ غيغابايتات) كي يصير التبديل
# ذرّيًّا فعلًا: مجلّدٌ جديدٌ كاملٌ يحلّ محلَّ القديم دفعةً واحدة.
"${SSH[@]}" "$HOST" "cp -al '$DEST/dl' '$STAGE/dl' 2>/dev/null || cp -a '$DEST/dl' '$STAGE/dl'"

# tar عبر الأنبوب لا rsync: أجهزةُ التطوير هنا ويندوز، وrsync ليس في Git Bash.
# ولا حاجةَ إلى `--delete` أصلًا — المرحلةُ تبدأ فارغةً إلّا من `dl/`، فالفكُّ فيها
# يعطي دلالةَ الحذف مجّانًا: ما لم يُبنَ هذه المرّة ليس موجودًا هناك.
# ⚠️ وهذا الوعدُ صادقٌ **بشرطِ** أن يبدأ `site/public/` نفسُه فارغًا — وكان لا
# يبدأ: البناءُ يكتب فوق الموجود، فصفحةٌ حُذفت من المصدر كانت تبقى في `public/`
# وتُحزَم وتُنشَر إلى الأبد. صار `build.py` يمحو المخرَجَ قبل البناء (بشاهدِ
# `.mihrab-site-build`)، ويحرسه [OUT-01]. والشاهدُ نفسُه لا يُشحَن.
# ⚠️ **و`--skip-old-files` شرطٌ لا زينة**: البناءُ يخبز `dl/releases.json` احتياطًا،
# والمرحلةُ بُذرت بـ`dl/` الحيّ — فالفكُّ بلا هذا الخيار يكتب المخبوزَ **فوق الحيّ**
# الذي رفعه `publish_release.sh` بعد آخرِ مزامنةٍ يدويّة، فيرتدّ جدولُ التنزيل إلى
# إصدارٍ أقدمَ بلا خطأٍ ولا ‎404‎ (قِيس محلّيًّا: `./dl/releases.json` في الأرشيف).
# المرحلةُ فارغةٌ إلّا من `dl/`، فالخيارُ لا يمسّ سواه: ما يوجد هناك يبقى، وما لا
# يوجد (مرآةٌ جديدة) يأخذ المخبوز.
tar -C "$PUB" --exclude='./.mihrab-site-build' -czf - . | "${SSH[@]}" "$HOST" "tar -C '$STAGE' --skip-old-files -xzf -"

# ⚠️ **والخيارُ نفسُه يجمّد المانيفستَ إن لم يُقارَن.** قِيس يومَ كُتب: الحيُّ
# والمخبوزُ بالإصدار نفسِه (‏1.121.05803) والحيُّ أصلُه الموضعُ القديم —
# فبـ`--skip-old-files` وحدَه لا يصل الأصلُ الجديدُ إلى الخادم أبدًا، وتبقى أزرارُ
# التنزيل تمرّ عبر الموضع القديم إلى الأبد. فالقاعدةُ إصدارٌ لا وجود: المخبوزُ يحلّ محلَّ الحيّ حين
# إصدارُه أحدث، أو مساوٍ ولا ينقصه أصلٌ من الحيّ (‏`base` مصحَّح)؛ ويُترَك الحيُّ حين هو
# الأحدث أو المساوي بأصلٍ زائد (رفعه `publish_release.sh` بعد آخر مزامنة) — ويُقال ذلك بصوت.
# والمساوي بأصلٍ واحدٍ (‏`id`) بملفٍّ أو بصمةٍ مختلفة لا يُحسَم: خروجٌ ‎2‎ حتّى يُزامَن المانيفست.
# ⚠️ **وغيابُ الحيّ (أوّلُ نشرٍ على مرآةٍ جديدة) ليس فشلَ ssh**: `cat` الغائبُ يُطوى
# بـ`|| true` **داخل** الخادم فيعود فارغًا ⇒ «لا شيء» ⇒ يحلّ المخبوز؛ أمّا سقوطُ ssh
# نفسِه فيُقال بصوت — كان `set -e` يُنهي السكربتَ عند الأنبوب بلا سطرٍ واحد.
# ⚠️ **ويُقرأ من `$DEST` لا من المرحلة**: الفكُّ أعلاه وضع المخبوزَ في المرحلة حين غاب
# الحيّ، فكانت قراءتُها تطبع «الإصدارُ واحد» لمرآةٍ جديدة (قِيس محلّيًّا) — القرارُ صائبٌ
# والسببُ المطبوعُ كاذب. و`$DEST/dl` هو ما بُذرت منه المرحلة، فالحيُّ فيهما واحد.
_live_json=$("${SSH[@]}" "$HOST" "cat '$DEST/dl/releases.json' 2>/dev/null || true") \
  || { echo "❌ تعذّرت قراءةُ المانيفست الحيّ من $HOST:$DEST/dl/ (ssh)" >&2; exit 1; }
# القرارُ في `build/lib/manifest_pick.py` لا هنا: وحدةٌ تُختبَر جدوليًّا في [MAN-01]
# (مرشَّحٌ لا يحلّ محلَّ نهائيّ، `v` البادئة، التساوي لا يمحو أصلًا رُفع بعد آخر مزامنة،
# وإصدارٌ غيرُ مفهومٍ أو أصلٌ ببصمتين أو معرِّفٌ مكرَّرٌ خطأٌ بصوت). والسببُ يُطبَع كما قالته الوحدة.
_newer=$(printf '%s' "$_live_json" | "$PY_BIN" "$HERE/build/lib/manifest_pick.py" "$PUB/dl/releases.json") \
  || { echo "❌ تعذّر الحسمُ بين المانيفستين — انظر السببَ أعلاه" >&2; exit 1; }
# وجوابٌ غيرُ الاثنين (وحدةٌ معطوبةٌ تخرج 0 بلا سطر) لا يُقرأ «الحيُّ يُترَك» صامتًا.
[[ "$_newer" == baked || "$_newer" == live ]] \
  || { echo "❌ ‏manifest_pick أجاب «$_newer» لا baked/live" >&2; exit 1; }
if [[ "$_newer" == baked ]]; then
  echo "▶ المانيفست: المخبوزُ يحلّ محلَّ الحيّ"
  # ⚠️ **إلى ملفٍّ مؤقّتٍ ثمّ `mv`، لا `cat >` على الملفّ نفسِه**: المرحلةُ بُذرت بـ`cp -al`
  # فـ`$STAGE/dl/releases.json` **رابطٌ صلبٌ** إلى الحيّ — والكتابةُ فيه تبتر الحيَّ وتكتبه
  # قبل التبديل الذرّيّ (قِيس محلّيًّا)، وتبقى فيه وإن فشل الإحلالُ وأُعيد الحيّ. والإعادةُ
  # بالاسم تفكّ الرابطَ في المرحلة وحدَها.
  "${SSH[@]}" "$HOST" "cat > '$STAGE/dl/.releases.json.new' && mv -f '$STAGE/dl/.releases.json.new' '$STAGE/dl/releases.json'" < "$PUB/dl/releases.json"
else
  echo "▶ المانيفست: الحيُّ يُترَك — زامِن site/data/releases.json"
fi

echo "▶ التبديلُ الذرّيّ…"
# إن نجحت إزاحةُ الحيّ وفشل إحلالُ المرحلة (صلاحيّة، قرص) يُعاد الحيُّ إلى مكانه —
# وإلّا بقي الجذرُ بلا `site/` والزائرُ أمام ‎404‎ حتّى يتدخّل أحد.
# ⚠️ **و`mv -T` لا `mv`**: إن فشلت الإزاحةُ (ويُطويها `|| true`) بقي `$DEST` قائمًا، و`mv`
# العاديّ ينقل المرحلةَ **داخلَه** (`site/.site.new/`) وينجح — فيُعلَن «نُشر» والحيُّ لم
# يتغيّر (قِيس محلّيًّا). و`-T` يرفض مجلّدًا غيرَ فارغ فيحمرّ. والإعادةُ مشروطةٌ بوجود
# `.old` كي لا تكذب رسالتُها حين لم يُزَح الحيُّ أصلًا.
"${SSH[@]}" "$HOST" "rm -rf '$ROOT/.$SUB.old' && mv -T '$DEST' '$ROOT/.$SUB.old' 2>/dev/null || true; mv -T '$STAGE' '$DEST' || { if [ -d '$ROOT/.$SUB.old' ] && [ ! -e '$DEST' ]; then mv -T '$ROOT/.$SUB.old' '$DEST'; fi; echo '❌ فشل الإحلالُ — الحيُّ في مكانه' >&2; exit 1; }; rm -rf '$ROOT/.$SUB.old'"

# ── ويُتحقَّق مما وصل، لا ممّا غادر ──
# قِيس فعلًا: نُقلت هويّةُ محرابٍ في المستودع كلِّه إلى منظّمته الجديدة، وخضَّ حارسُ
# الشجرةَ المتعقَّبةَ فمرّ بحقّ — لأنّ المصدرَ صحيحٌ فعلًا. وبقيت صفحةُ
# التنزيل المنشورةُ أسبوعًا تحمل الاسمَ القديمَ في كلّ رابطٍ فيها، لأنّ أحدًا لم
# يُعِد النشر. **وما يراه المستخدمُ ليس الشجرةَ المتعقَّبة بل ما يردّه الخادم.**
#
# فالبوّابةُ هنا لا في مُدقِّقٍ ثابت: القياسُ يحتاج شبكةً بحكم طبيعته، وموضعُه
# اللحظةُ التي يقع فيها الفعلُ — كنظيرتها في `publish_release_notes.sh`.
ORG=$("$PY_BIN" - "$HERE/site/data/site.json" <<'PY'
import json, sys, re
repo = json.load(open(sys.argv[1], encoding="utf-8")).get("repo", "")
m = re.search(r"github\.com/([^/]+)/", repo)
print(m.group(1) if m else "")
PY
)
[[ -n "$ORG" ]] || { echo "❌ تعذّر اشتقاقُ المنظّمة من site/data/site.json" >&2; exit 1; }

# والأصلُ يُشتقّ من `canonical` لا يُكتَب هنا: نسخةٌ ثانيةٌ من العنوان تنحرف
# بصمتٍ يومَ ينتقل الموقعُ ثانيةً، فيتحقّق الناشرُ من عنوانٍ لم يعد أحدٌ يطلبه.
BASE=$("$PY_BIN" - "$HERE/site/data/site.json" <<'PY'
import json, sys
print(json.load(open(sys.argv[1], encoding="utf-8")).get("canonical", "").rstrip("/"))
PY
)
[[ -n "$BASE" ]] || { echo "❌ لا canonical في site/data/site.json" >&2; exit 1; }

echo "▶ التحقّقُ من $BASE (المنظّمة: $ORG) …"
_fails=0
for _page in "" "download/" "docs/"; do
  _url="$BASE/$_page"
  _body=$(curl -fsS --max-time 20 "$_url" 2>/dev/null) || {
    echo "   ❌ $_url — تعذّر الجلب" >&2; _fails=$((_fails + 1)); continue; }
  # **أيُّ منظّمةٍ غيرِ منظّمتنا في رابط مستودعٍ لنا**: لا يُكتَب الاسمُ القديمُ هنا
  # حرفيًّا، فهو يتقادم مع كلّ نقلة. يُسأل السؤالُ الصحيح: أكلُّ رابطٍ إلى مستودعٍ
  # اسمُه `mihrab*` يحمل منظّمتَنا؟
  _stale=$(printf '%s' "$_body" \
    | grep -oE 'github\.com/[A-Za-z0-9_-]+/mihrab[A-Za-z0-9_-]*' \
    | grep -v "github.com/$ORG/" | sort -u || true)
  if [[ -n "$_stale" ]]; then
    echo "   ❌ $_url يحمل مراجعَ لمنظّمةٍ أخرى:" >&2
    printf '      %s\n' $_stale >&2
    _fails=$((_fails + 1))
  else
    echo "   ✅ ${_page:-/}"
  fi
done
# **وسببان لا سبب**: صفحةٌ تحمل اسمًا قديمًا تعني مصدرًا لم يُصحَّح؛ وصفحةٌ لا تُجلَب
# أصلًا تعني أنّ الخادمَ لا يخدم هذا الأصلَ بعدُ — وهي حالةٌ مختلفةٌ تمامًا، وقعت
# فعلًا يومَ نُشر المحتوى قبل تبديل كتلة nginx. ورسالةٌ واحدةٌ لهما تُرسِل القارئَ
# يصحّح ملفًّا سليمًا.
[[ "$_fails" -eq 0 ]] || {
  echo "❌ نُشرت الشجرةُ ولم يُقَس وصولُها:" >&2
  echo "   • إن كان الفشلُ «تعذّر الجلب» — فالمحتوى على القرص ولا كتلةَ nginx تخدمه" >&2
  echo "     على هذا الأصل بعد. ركّبِ الكتلةَ ثمّ أعِد النشرَ للتحقّق." >&2
  echo "   • وإن كان «يحمل مراجعَ لمنظّمةٍ أخرى» — فصحّحْ site/data/site.json وأعِد البناء." >&2
  exit 1; }

# ── والمجسُّ الحيّ [LIVE-01]: ما لا تراه المنظّمةُ ──
# المنظّمةُ تقيس النصّ؛ والمجسُّ يقيس السطوحَ التي أوقعتنا قبلًا: ‎404‎ صفحتُنا لا
# nginx العارية، والخطوطُ تصل بـCORS، و`dl/releases.json` يُخدَم وأصولُه معه.
# يُشغَّل هنا لا في الجدولة وحدَها: اللحظةُ التي يقع فيها الفعل.
echo "▶ المجسُّ الحيّ…"
"$PY_BIN" "$HERE/tests/live/probe_live.py" || {
  echo "❌ نُشرت الشجرةُ والمجسُّ الحيّ أحمر — اقرأ سطورَه أعلاه؛ ما يخصّ nginx يُصلَح" >&2
  echo "   في كتل nginx ثمّ يُعاد النشرُ للتحقّق." >&2; exit 1; }

echo "✅ نُشر: $BASE/"
echo "   الثنائيّات:  $DEST/dl/   (لم تُمَسّ)"
