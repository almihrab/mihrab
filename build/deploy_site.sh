#!/usr/bin/env bash
# نشرُ موقع محراب على خادمنا → https://sad-lang.org/mihrab/
#
# لماذا خادمنا لا GitHub Pages وحده؟ الثنائيّات. مثبِّتُ محراب يقارب ٣٠٠ ميغابايت،
# وGitHub Pages لا يستضيف مخرجاتِ بناءٍ أصلًا (والمستودعُ ليس مخزنَ ملفّات). والخادمُ
# يملك ٥٤٦ غيغابايت حرّة وعرضَ نطاقٍ لنا، والنطاقُ `sad-lang.org` نطاقُ العائلة نفسِها
# — فمحرابٌ يسكن مع لغة ص لا في جزيرةٍ اسمُها `github.io`.
#
# وGitHub Pages يبقى **مرآةً** ينشرها CI من المولِّد نفسِه، فلا انجرافَ بين النسختين.
#
# ⚠️ ثلاثةُ قيودٍ يفرضها الخادم، وكلُّها مقصودةٌ في هذا السكربت:
#   ١) لا sudo بلا كلمةِ مرور ⇒ لا vhost جديد ولا شهادةَ نطاقٍ فرعيّ. ولا حاجة:
#      كتلةُ `location /` في vhost القائم فيها `try_files $uri $uri/`، فأيّ مجلّدٍ
#      فرعيّ تحت /opt/sad-website يُخدَم فورًا بشهادةِ sad-lang.org نفسِها.
#   ٢) `dl/` **مستثنى من --delete**: الثنائيّات تُرفَع مرّةً وتبقى، وبناءُ الموقع لا
#      يعرف بها. بلا هذا الاستثناء يمسح أوّلُ نشرٍ كلَّ ملفّاتِ التنزيل.
#   ٣) النقلُ إلى مجلّدٍ مؤقّت ثمّ تبديلٌ ذرّيّ: rsync مباشرةً على المجلّد الحيّ يترك
#      الزائرَ في منتصف النقل أمام صفحةٍ بأصولٍ ناقصة.
set -euo pipefail

# ⚠️ لا قيمةَ افتراضيّة للمضيف: المستودعُ عامّ، واسمُ مستخدمٍ ومنفذٌ غيرُ قياسيٍّ
# مكتوبان في الشيفرة استطلاعٌ مجّانيٌّ لمن يقرأ. ليسا سرًّا، لكنّ نشرَهما لا يفيد
# أحدًا إلّا من يبحث عن بابٍ يطرقه. الناشرُ يعرف مضيفَه فليمرّره:
#   MIHRAB_SITE_HOST=user@host bash build/deploy_site.sh
HOST="${MIHRAB_SITE_HOST:?عيّن MIHRAB_SITE_HOST (مثال: user@host)}"
PORT="${MIHRAB_SITE_PORT:-22}"
# ── الوجهةُ صارت نطاقَ محرابٍ نفسَه ──
# كان الموقعُ يسكن `/opt/sad-website/mihrab` ويُخدَم من `sad-lang.org/mihrab/`، وكان
# جذرُ `mihrab.dev` للمحرِّر. فانقلبا: الجذرُ للموقع، والمحرِّرُ إلى `app.mihrab.dev`.
ROOT="${MIHRAB_SITE_ROOT:-/opt/mihrab}"
SUB="${MIHRAB_SITE_SUBDIR:-site}"

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

# مفسّرُ بايثون يُحلّ ولا يُفترَض: `python` المجرَّد غائبٌ عن أوبونتو 24.04.
. "$HERE/build/lib/pybin.sh"
resolve_py_bin || exit 1
PUB="$HERE/site/public"

SSH=(ssh -p "$PORT" -o BatchMode=yes)

echo "▶ بناءُ الموقع…"
"$PY_BIN" "$HERE/site/build.py"

[[ -f "$PUB/index.html" ]] || { echo "❌ لا مخرَجَ في $PUB" >&2; exit 1; }

DEST="$ROOT/$SUB"
STAGE="$ROOT/.$SUB.new"

echo "▶ النقلُ إلى $HOST:$STAGE …"
"${SSH[@]}" "$HOST" "rm -rf '$STAGE' && mkdir -p '$STAGE' '$DEST/dl'"

# نبذر المرحلةَ بـ dl/ الحاليّ (روابطٌ صلبة، بلا نقلِ غيغابايتات) كي يصير التبديل
# ذرّيًّا فعلًا: مجلّدٌ جديدٌ كاملٌ يحلّ محلَّ القديم دفعةً واحدة.
"${SSH[@]}" "$HOST" "cp -al '$DEST/dl' '$STAGE/dl' 2>/dev/null || cp -a '$DEST/dl' '$STAGE/dl'"

# tar عبر الأنبوب لا rsync: أجهزةُ التطوير هنا ويندوز، وrsync ليس في Git Bash.
# ولا حاجةَ إلى `--delete` أصلًا — المرحلةُ تبدأ فارغةً إلّا من `dl/`، فالفكُّ فيها
# يعطي دلالةَ الحذف مجّانًا: ما لم يُبنَ هذه المرّة ليس موجودًا هناك.
tar -C "$PUB" -czf - . | "${SSH[@]}" "$HOST" "tar -C '$STAGE' -xzf -"

echo "▶ التبديلُ الذرّيّ…"
"${SSH[@]}" "$HOST" "rm -rf '$ROOT/.$SUB.old' && mv '$DEST' '$ROOT/.$SUB.old' 2>/dev/null || true; mv '$STAGE' '$DEST' && rm -rf '$ROOT/.$SUB.old'"

# ── ويُتحقَّق مما وصل، لا ممّا غادر ──
# قِيس فعلًا: نُقلت هويّةُ محرابٍ في المستودع كلِّه إلى منظّمته الجديدة، وخضَّ حارسُ
# ‏[ORG-01] الشجرةَ المتعقَّبةَ فمرّ بحقّ — لأنّ المصدرَ صحيحٌ فعلًا. وبقيت صفحةُ
# التنزيل المنشورةُ أسبوعًا تحمل الاسمَ القديمَ في كلّ رابطٍ فيها، لأنّ أحدًا لم
# يُعِد النشر. **وما يراه المستخدمُ ليس الشجرةَ المتعقَّبة بل ما يردّه الخادم.**
#
# فالبوّابةُ هنا لا في مُدقِّقٍ ثابت: القياسُ يحتاج شبكةً بحكم طبيعته، وموضعُه
# اللحظةُ التي يقع فيها الفعلُ — كنظيرتها في `publish_release_notes.sh`.
ORG=$("$PY_BIN" - "$HERE/site/data/site.json" <<'PY'
import json, sys, re
repo = json.load(open(sys.argv[1], encoding="utf-8")).get("repo", "")
m = re.search(r"github\.com/([^/]+)/", repo)
print(m.group(1) if m else "")
PY
)
[[ -n "$ORG" ]] || { echo "❌ تعذّر اشتقاقُ المنظّمة من site/data/site.json" >&2; exit 1; }

# والأصلُ يُشتقّ من `canonical` لا يُكتَب هنا: نسخةٌ ثانيةٌ من العنوان تنحرف
# بصمتٍ يومَ ينتقل الموقعُ ثانيةً، فيتحقّق الناشرُ من عنوانٍ لم يعد أحدٌ يطلبه.
BASE=$("$PY_BIN" - "$HERE/site/data/site.json" <<'PY'
import json, sys
print(json.load(open(sys.argv[1], encoding="utf-8")).get("canonical", "").rstrip("/"))
PY
)
[[ -n "$BASE" ]] || { echo "❌ لا canonical في site/data/site.json" >&2; exit 1; }

echo "▶ التحقّقُ من $BASE (المنظّمة: $ORG) …"
_fails=0
for _page in "" "download/" "docs/"; do
  _url="$BASE/$_page"
  _body=$(curl -fsS --max-time 20 "$_url" 2>/dev/null) || {
    echo "   ❌ $_url — تعذّر الجلب" >&2; _fails=$((_fails + 1)); continue; }
  # **أيُّ منظّمةٍ غيرِ منظّمتنا في رابط مستودعٍ لنا**: لا يُكتَب الاسمُ القديمُ هنا
  # حرفيًّا، فهو يتقادم مع كلّ نقلة. يُسأل السؤالُ الصحيح: أكلُّ رابطٍ إلى مستودعٍ
  # اسمُه `mihrab*` يحمل منظّمتَنا؟
  _stale=$(printf '%s' "$_body" \
    | grep -oE 'github\.com/[A-Za-z0-9_-]+/mihrab[A-Za-z0-9_-]*' \
    | grep -v "github.com/$ORG/" | sort -u || true)
  if [[ -n "$_stale" ]]; then
    echo "   ❌ $_url يحمل مراجعَ لمنظّمةٍ أخرى:" >&2
    printf '      %s\n' $_stale >&2
    _fails=$((_fails + 1))
  else
    echo "   ✅ ${_page:-/}"
  fi
done
# **وسببان لا سبب**: صفحةٌ تحمل اسمًا قديمًا تعني مصدرًا لم يُصحَّح؛ وصفحةٌ لا تُجلَب
# أصلًا تعني أنّ الخادمَ لا يخدم هذا الأصلَ بعدُ — وهي حالةٌ مختلفةٌ تمامًا، وقعت
# فعلًا يومَ نُشر المحتوى قبل تبديل كتلة nginx. ورسالةٌ واحدةٌ لهما تُرسِل القارئَ
# يصحّح ملفًّا سليمًا.
[[ "$_fails" -eq 0 ]] || {
  echo "❌ نُشرت الشجرةُ ولم يُقَس وصولُها:" >&2
  echo "   • إن كان الفشلُ «تعذّر الجلب» — فالمحتوى على القرص ولا كتلةَ nginx تخدمه" >&2
  echo "     على هذا الأصل بعد. ركّبِ الكتلةَ ثمّ أعِد النشرَ للتحقّق." >&2
  echo "   • وإن كان «يحمل مراجعَ لمنظّمةٍ أخرى» — فصحّحْ site/data/site.json وأعِد البناء." >&2
  exit 1; }

echo "✅ نُشر: $BASE/"
echo "   الثنائيّات:  $DEST/dl/   (لم تُمَسّ)"
